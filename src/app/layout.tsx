/**
 * The auth server is contacted during every session check, and it normally sits
 * on a different origin than the app. Opening the connection early (DNS, TCP,
 * TLS) removes that handshake from the critical path of the first server call
 * the browser makes after hydration.
 */
function supabaseOrigin(): string | null {
  try {
    const config = readSupabaseConfig();
    return config ? new URL(config.url).origin : null;
  } catch {
    return null;
  }
}

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const authOrigin = supabaseOrigin();

  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={`${fontSans.variable} ${fontMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col bg-background text-foreground font-sans selection:bg-primary/15 selection:text-primary">
        {authOrigin ? (
          <link rel="preconnect" href={authOrigin} crossOrigin="anonymous" />
        ) : null}
        <ThemeProvider
          attribute="class"
          defaultTheme="system"
          enableSystem
          disableTransitionOnChange
        >
          {children}
        </ThemeProvider>
        <VitalsReporter />
      </body>
    </html>
  );
}
