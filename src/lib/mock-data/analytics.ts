const defaultGenderBreakdown = (m: number, f: number, o = 0): GenderBreakdown => {
  const total = m + f + o;
  return {
    male: m,
    female: f,
    other: o,
    total,
    malePercent: total > 0 ? Number(((m / total) * 100).toFixed(1)) : null,
    femalePercent: total > 0 ? Number(((f / total) * 100).toFixed(1)) : null,
    otherPercent: total > 0 ? Number(((o / total) * 100).toFixed(1)) : null,
  };
};

